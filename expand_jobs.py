def classify_existing(j):
    """现有数据（全部来自技术种子）归为技术研发；保留其原有类目若已存在。"""
    if j.get("category"):
        return j["category"]
    return "技术研发"


def main():
    with open(JOBS_PATH, encoding="utf-8") as f:
        jobs = json.load(f)

    # 1) 给现有岗位补 category
    for j in jobs:
        j["category"] = classify_existing(j)

    seen = set()
    for j in jobs:
        seen.add((j["company"], j["title"], j["city"], (j.get("requirements") or "")[:24], j["category"]))

    new_jobs = []
    for cat, spec in CATALOG.items():
        if cat == "技术研发" or not spec["titles"]:
            continue  # 技术研发已有大量数据，不追加
        rnd = random.Random(SEED + hash(cat) % 100000)
        count = 0
        attempts = 0
        while count < TARGET_PER_CATEGORY and attempts < TARGET_PER_CATEGORY * 12:
            attempts += 1
            city = rnd.choice(CITIES)
            title = rnd.choice(spec["titles"])
            etype = rnd.choices(["实习", "校招", "社招"], weights=[3, 3, 4])[0]
            edu = rnd.choice(spec["edu_dist"])
            exp = exp_for(etype, rnd)
            company = gen_company(city, spec["industries"], rnd)
            req = rnd.choice(spec["reqs"]).replace("{city}", city)
            ntag = min(len(spec["tags"]), rnd.randint(2, 4))
            tags = rnd.sample(spec["tags"], k=ntag)
            salary = salary_for(etype, edu, rnd)
            key = (company, title, city, req[:24], cat)
            if key in seen:
                continue
            seen.add(key)
            new_jobs.append({
                "company": company, "title": title, "city": city,
                "type": etype, "salary": salary, "edu": edu, "exp": exp,
                "requirements": req, "tags": tags, "category": cat,
                "source": "category-expanded", "updated": "2026-09",
            })
            count += 1

    jobs.extend(new_jobs)

    # 重排 id，避免与现有 id 冲突/重复
    for i, j in enumerate(jobs, 1):
        j["id"] = i

    with open(JOBS_PATH, "w", encoding="utf-8") as f:
        json.dump(jobs, f, ensure_ascii=False, indent=2)

    # 统计
    import collections
    by_cat = collections.Counter(j["category"] for j in jobs)
    print(f"完成：原 {len(jobs)-len(new_jobs)} 条 + 新增 {len(new_jobs)} 条 = 共 {len(jobs)} 条")
    print("职能类别分布：")
    for k, v in by_cat.most_common():
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
